"""Single-file launcher for the shareable Windows sample.

Serves the built wiki over HTTP on localhost and opens it in the default browser.
The data folder (db.sqlite3 + the Vite bundle) lives next to the .exe, so the sample
carries no source. Two builds come out of packaging/build-sample.ps1: the one the
owner hands over by hand embeds its provider keys in the binary, and the
bring-your-own-key one reads the runner's environment or a `.env` placed beside the
.exe. Neither shape hides anything from whoever holds the folder — see the README's
sample section for what each one costs. Without any key at all the sample degrades to
the local tables instead of breaking.

Run through PyInstaller — see packaging/esi-wiki-sample.spec.
"""

import os
import shutil
import socket
import sys
import threading
import webbrowser
from pathlib import Path


def bundle_root() -> Path:
    """Directory holding files packed with --add-data."""
    return Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent))


def data_root() -> Path:
    """Writable folder next to the executable that carries the wiki data."""
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return bundle_root() / "sample-data"


def free_port(first: int, attempts: int = 12) -> int:
    for port in range(first, first + attempts):
        with socket.socket() as probe:
            try:
                probe.bind(("127.0.0.1", port))
                return port
            except OSError:
                continue
    return first


def read_env_file(path: Path) -> dict:
    """Names of the variables a `.env` sets to a non-empty value. Values are never kept or shown."""
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return {}
    found = {}
    for line in lines:
        if line.lstrip().startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        name = name.strip()
        if name.endswith("_API_KEY") and value.strip().strip("\"'"):
            found[name] = True
    return found


def prepare(env: dict) -> Path:
    root = data_root()
    src_db = bundle_root() / "db.sqlite3"
    if not src_db.exists():
        # Running from source rather than a packaged build: use the repo's own paths.
        return root

    root.mkdir(parents=True, exist_ok=True)
    db = root / "db.sqlite3"
    if not db.exists():
        shutil.copy(src_db, db)

    # settings.py resolves the bundle as REPO_ROOT/frontend/dist, so mirror that shape.
    dist = root / "frontend" / "dist"
    if not dist.exists():
        shutil.copytree(bundle_root() / "dist", dist)

    env["WIKI_ROOT"] = str(root)
    env["WIKI_DB"] = str(db)
    env["DJANGO_DEBUG"] = "0"
    env["DJANGO_ALLOWED_HOSTS"] = "127.0.0.1,localhost"
    # The sample has no external integrations; a stable local secret keeps Django happy.
    env.setdefault("DJANGO_SECRET_KEY", "sample-build-local-only-not-a-secret")
    # Two builds come out of the same script. The owner's carries `embedded_keys.py` (generated by
    # packaging/keys_embed.py), so the AI answers on a machine with nothing installed and nothing
    # configured. The bring-your-own-key build carries no such module, and then the runner's own
    # environment is the key source — plus a `.env` beside the .exe, which settings.py loads
    # through WIKI_ROOT above. No keys anywhere: the assistant answers from the local tables.
    try:
        from embedded_keys import KEYS
    except ImportError:  # the bring-your-own-key build: no module, no embedded secret
        KEYS = {}
    else:
        env.update({name: value for name, value in KEYS.items() if value})

    lanes = (("GEMINI_API_KEY", "Gemini"), ("NVIDIA_API_KEY", "NVIDIA"),
             ("OPENROUTER_API_KEY", "OpenRouter"), ("OPENAI_API_KEY", "OpenAI"))
    # The banner runs before Django's settings load the `.env` beside the .exe, so reading
    # os.environ alone reports "absente" for a key that is in fact configured. Look at both.
    from_file = read_env_file(root / ".env")
    for name, lane in lanes:
        if env.get(name):
            print(f"Clé {lane} : présente — le niveau modèle répond.")
        elif name in from_file:
            print(f"Clé {lane} : présente (.env à côté de l'.exe) — le niveau modèle répond.")
        elif name not in KEYS:
            print(f"Clé {lane} : absente — Posez un .env à côté de l'.exe ou exportez la variable, "
                  "sinon l'assistant répond depuis les tables.")
    if env.get("OPENAI_API_KEY") or "OPENAI_API_KEY" in from_file:
        # The one provider here that bills per token; tried last, after the three free lanes.
        print("Attention : OpenAI est payant à l'usage — ce lane n'est essayé qu'en dernier.")
    return root


def main() -> None:
    root = prepare(os.environ)
    port = free_port(8013)

    backend = bundle_root() / "backend"
    if not backend.exists():
        backend = Path(__file__).resolve().parent.parent / "backend"
    sys.path.insert(0, str(backend))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")

    import django

    django.setup()
    from django.core.wsgi import get_wsgi_application

    application = get_wsgi_application()

    from waitress import serve

    url = f"http://127.0.0.1:{port}"
    print(f"Wiki ESI — sample : {url}")
    print(f"Données           : {root}")
    print("Fermer cette fenêtre arrête le serveur.")
    threading.Timer(1.2, lambda: webbrowser.open(url)).start()
    serve(application, host="127.0.0.1", port=port, threads=8)


if __name__ == "__main__":
    main()
