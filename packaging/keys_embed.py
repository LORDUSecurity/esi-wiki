"""Write the provider keys into a module that the sample's build packs inside the .exe.

    python packaging/keys_embed.py embed     # read .env, generate packaging/embedded_keys.py
    python packaging/keys_embed.py clear     # remove the generated module

This is the build the owner shares by hand, with a known handful of people: the keys ride along
in the clear rather than behind a seal, because there is nothing for the recipient to break, set
up, or forget. `launcher.py` puts them in the process environment at startup.

The generated file holds live keys, so `packaging/embedded_keys.py` is gitignored and must never
be staged. For the build a stranger gets - bring your own key - do not embed: the launcher then
honours the runner's own environment and a `.env` placed next to the .exe.
"""

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
ENV_FILE = REPO / ".env"
TARGET = HERE / "embedded_keys.py"

KEY_NAMES = ("GEMINI_API_KEY", "NVIDIA_API_KEY", "OPENROUTER_API_KEY", "OPENAI_API_KEY")

# What a key from each provider starts with — the same rule backend/aichat/views.py applies before
# sending one, and the same forms .env.example documents. Google issues two shapes (the long-standing
# AIza… and the newer AQ.… AI Studio hands out), so a single prefix would reject a working key.
PREFIXES = {
    "GEMINI_API_KEY": ("AIza", "AQ."),
    "NVIDIA_API_KEY": ("nvapi-",),
    "OPENROUTER_API_KEY": ("sk-or-",),
    "OPENAI_API_KEY": ("sk-proj-", "sk-svcacct-", "sk-"),
}

# The OpenAI key shares its `sk-` opening with OpenRouter's `sk-or-`, so a token can match both
# tables. views.py refuses to send such a key to the host that did not mint it; the warning here
# says so at build time instead of letting the lane die quietly on the first chat.
REJECTS = {"OPENAI_API_KEY": ("sk-or-",)}


def read_values():
    """The repo's .env first, then the machine's own environment."""
    values = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            name, _, raw = line.partition("=")
            name, raw = name.strip(), raw.strip().strip('"').strip("'")
            if name in KEY_NAMES and raw:
                values[name] = raw
    for name in KEY_NAMES:
        if os.getenv(name, "").strip():
            values[name] = os.getenv(name).strip()
    return values


def embed() -> int:
    values = read_values()
    if not values:
        print("Aucune clé dans .env : build sans clé embarquée (le sample lira l'environnement "
              "du destinataire).")
        return 0
    for name, value in sorted(values.items()):
        if value.startswith(REJECTS.get(name, ())):
            print(f"Attention : {name} a le format d'un autre fournisseur — le wiki l'ignorera "
                  "plutôt que de l'envoyer au mauvais hôte.")
        elif not value.startswith(PREFIXES[name]):
            print(f"Attention : {name} ne commence par aucune forme connue "
                  f"({' ou '.join(PREFIXES[name])}…) — le wiki l'ignorera au premier chat.")
    if "OPENAI_API_KEY" in values:
        # The one lane here that bills. Whoever holds the folder could spend money, not just quota.
        print("Rappel : OPENAI_API_KEY est embarquée — ce compte est facturé à l'usage, "
              "contrairement aux trois autres. Quiconque tient le dossier peut dépenser.")
    body = "\n".join(
        f'    "{name}": {values[name]!r},' for name in KEY_NAMES if name in values
    )
    TARGET.write_text(
        '"""Generated by packaging/keys_embed.py — holds live keys, never commit this.\n'
        'Regenerate with `embed`, remove with `clear`, then rebuild the sample."""\n\n'
        f"KEYS = {{\n{body}\n}}\n",
        encoding="utf-8",
    )
    print(f"Clés embarquées : {len(values)} ({', '.join(n.split('_')[0].lower() for n in values)}) "
          f"— {TARGET.name}, à ne jamais committer.")
    return len(values)


def clear() -> None:
    if TARGET.exists():
        TARGET.unlink()
        print(f"{TARGET.name} supprimé : le prochain build sera un build à clé du destinataire.")
    else:
        print(f"Rien à supprimer : {TARGET.name} est absent.")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "embed"
    embed() if command == "embed" else clear()
